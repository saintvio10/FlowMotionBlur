inline const Glyph* Find(char c)
{
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    for (const Glyph& g : kFont) if (g.c == c) return &g;
    return &kFont[0];
}

// Schreibt Textzeilen (weiss auf schwarzem Kasten) oben links ins Bild.
inline void DrawLines(fmb::RGBAImage& img, const std::vector<std::string>& lines)
{
    if (img.w <= 0 || img.h <= 0 || lines.empty()) return;
    size_t maxLen = 0;
    for (const auto& l : lines) maxLen = std::max(maxLen, l.size());
    // Schriftgroesse so waehlen, dass die laengste Zeile ins Bild passt
    int s = std::max(1, std::min(img.h / 160, static_cast<int>((img.w - 8) / (6 * std::max<size_t>(1, maxLen)))));
    const int lineH = 9 * s, boxW = std::min<int>(img.w, static_cast<int>(maxLen) * 6 * s + 4 * s);
    const int boxH = std::min<int>(img.h, static_cast<int>(lines.size()) * lineH + 4 * s);
    for (int y = 0; y < boxH; ++y)
        for (int x = 0; x < boxW; ++x) { float* p = img.px(x, y); p[0] = p[1] = p[2] = 0.f; p[3] = 1.f; }
    for (size_t li = 0; li < lines.size(); ++li) {
        int y0 = 2 * s + static_cast<int>(li) * lineH;
        for (size_t ci = 0; ci < lines[li].size(); ++ci) {
            const Glyph* g = Find(lines[li][ci]);
            int x0 = 2 * s + static_cast<int>(ci) * 6 * s;
            for (int r = 0; r < 7; ++r)
                for (int c = 0; c < 5; ++c) {
                    if (g->rows[r][c] != '#') continue;
                    for (int dy = 0; dy < s; ++dy)
                        for (int dx = 0; dx < s; ++dx) {
                            int x = x0 + c * s + dx, y = y0 + r * s + dy;
                            if (x < img.w && y < img.h) { float* p = img.px(x, y); p[0] = p[1] = p[2] = 1.f; p[3] = 1.f; }
                        }
                }
        }
    }
}

